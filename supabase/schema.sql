create table if not exists public.stories (
  id         bigint generated by default as identity primary key,
  title      text not null,
  body       text not null,               -- HTML from the rich text editor
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.stories enable row level security;

-- Anyone can read stories.
drop policy if exists "stories are public" on public.stories;
create policy "stories are public" on public.stories
  for select using (true);

-- Only logged-in users (you) can add / edit / delete.
-- Turn OFF public sign-ups (Authentication -> Sign In / Providers -> "Allow new users to sign up")
-- after creating your own user, so nobody else can get an account.
drop policy if exists "admins insert" on public.stories;
create policy "admins insert" on public.stories
  for insert to authenticated with check (true);

drop policy if exists "admins update" on public.stories;
create policy "admins update" on public.stories
  for update to authenticated using (true) with check (true);

drop policy if exists "admins delete" on public.stories;
create policy "admins delete" on public.stories
  for delete to authenticated using (true);

