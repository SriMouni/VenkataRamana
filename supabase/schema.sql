-- ---------- Photo gallery ----------
create table if not exists public.photos (
  id         bigint generated by default as identity primary key,
  url        text not null,
  path       text not null,            -- file path inside the 'media' storage bucket
  caption    text,
  kind       text not null default 'photo',   -- 'photo' (gallery) or 'cartoon'
  created_at timestamptz not null default now()
);
alter table public.photos add column if not exists kind text not null default 'photo';
drop table if exists public.videos;
alter table public.photos enable row level security;
drop policy if exists "photos are public" on public.photos;
create policy "photos are public" on public.photos for select using (true);
drop policy if exists "admins write photos" on public.photos;
create policy "admins write photos" on public.photos
  for all to authenticated using (true) with check (true);

-- ---------- Storage bucket for uploaded images ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('media', 'media', true, 10485760, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do nothing;

drop policy if exists "media public read" on storage.objects;
create policy "media public read" on storage.objects for select using (bucket_id = 'media');
drop policy if exists "media admin upload" on storage.objects;
create policy "media admin upload" on storage.objects for insert to authenticated with check (bucket_id = 'media');
drop policy if exists "media admin delete" on storage.objects;
create policy "media admin delete" on storage.objects for delete to authenticated using (bucket_id = 'media');
